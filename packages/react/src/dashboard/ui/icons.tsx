/**
 * The handful of Phosphor icons the dashboard uses, inlined at the single weight
 * each one is drawn at. The npm package builds a Map of all six weights per icon
 * inside a constructor call, which no bundler can shake apart, so importing 15
 * icons from it costs ~41KB. These paths are the same artwork at ~3KB.
 *
 * Phosphor Icons, MIT (c) 2023 Phosphor Icons — https://phosphoricons.com
 */
export type IconProps = Omit<SVGProps<SVGSVGElement>, "size"> & {
  size?: number;
  /** Flips the icon horizontally, matching Phosphor's prop of the same name. */
  mirrored?: boolean;
};

/** Phosphor draws on a 256x256 grid and fills, so icons take the surrounding text colour. */
function icon(name: string, d: string) {
  function Icon({ size = 16, mirrored, ...props }: IconProps) {
    return (
      <svg
        viewBox="0 0 256 256"
        width={size}
        height={size}
        fill="currentColor"
        transform={mirrored ? "scale(-1, 1)" : undefined}
        {...props}
      >
        <path d={d} />
      </svg>
    );
  }
  Icon.displayName = name;
  return Icon;
}

